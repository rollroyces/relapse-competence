#!/usr/bin/env python3
"""Regenerate the gap audit report's revision-history table.

The table lists every commit that touched the report. Commit *subjects* are
stable across a history rewrite, commit *hashes* are not -- so the table is
regenerated from the log rather than maintained by hand.

Run this after any amend of the history:

    python scripts/regenerate_revision_history.py

It is idempotent: running it twice on an unchanged history is a no-op.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPORT_PATH = "docs/GAP-AUDIT-BIOELECTRIC.md"

TABLE_HEADER = "| Commit | Change | Where the retracted wording now lives |\n|---|---|---|\n"

#: Subject -> what that commit changed. Subjects survive a history rewrite;
#: hashes do not, which is why this file is keyed on subjects.
DESCRIPTIONS: dict[str, str] = {
    "Initial release: executable longitudinal cfDNA evidence chain":
        "Initial release: the simulator, detectors, benchmark engine and evidence chain",
    "Add local CI script and document the Actions fallback":
        "Local CI script added and documented, as a fallback while Actions is unavailable",
    "Fix PYTHONPATH in local CI script":
        "Local CI script path fix",
    "Formal gap audit: bioelectric state x lung-cancer relapse competence":
        "**First publication of the gap audit. Its commit message was amended on "
        "2026-11-06** (see the note below).",
    "Audit corrections: parser reconciliation, false-positive attribution, G.3 accuracy":
        "Parser reconciliation; attribution corrected; G.3 rewritten; set-based "
        "comparison recommended. **Its commit message was amended on 2026-11-06.**",
    "Evidence the parser fix: identify and recover the four dropped book records":
        "The four dropped book records identified and recovered",
    "D1 executed: does a bulk ion-channel channel earn its read budget?":
        "D1 executed: channel allocation, specificity decomposition, and the "
        "carrying-capacity fix",
    "Close documentation drift after D1; extend the verifier to guard prose":
        "Documentation synchronised with the executed D1; verifier extended to "
        "guard prose. **Its commit message was amended on 2026-11-06.**",
    "Machine-checked disposition for the audit review findings":
        "Machine-generated findings disposition added",
    "Dual licence AGPL-3.0-or-later + commercial; stop restating retracted claims":
        "Licence migrated to AGPL-3.0-or-later plus commercial; retracted wording "
        "removed from the report body",
    "Executable research plan: eliminating the relapse-competent state in lung cancer":
        "Executable research plan added",
    "Two-sided proof of the audit findings, plus a revision history in the report":
        "Two-sided historical proof of each finding; revision history added to the report",
    "Remove every surviving copy of the withdrawn wording from the repository":
        "Withdrawn wording removed from every repository file; recovered from git "
        "at run time instead",
    "Regenerate the findings disposition against the current head":
        "Disposition artefact regenerated against the current head",
    "Amend two commit messages; make the commit reference resolve by content":
        "Two commit messages amended; the commit reference made to resolve by content",
    "Amend the remaining commit message; regenerate the revision history":
        "Remaining commit message amended; revision history regenerated by script",
}


def _git(*args: str) -> str:
    out = subprocess.run(
        ["git", *args], capture_output=True, text=True, check=True
    )
    return out.stdout


def build_table() -> tuple[str, str]:
    """Return (table_body, first_published_sha)."""
    log = _git("log", "--reverse", "--format=%H%x1f%s").strip().splitlines()
    rows: list[str] = []
    for line in log:
        sha, subject = line.split("\x1f", 1)
        desc = DESCRIPTIONS.get(subject, subject)
        where = (
            "git history at the first-published commit"
            if subject.startswith("Formal gap audit")
            else "—"
        )
        rows.append(f"| `{sha[:7]}` | {desc} | {where} |")
    rows.append("| *(this commit)* | Revision history regenerated from the log | — |")

    first = (
        _git(
            "log",
            "--diff-filter=A",
            "--format=%H",
            "--",
            REPORT_PATH,
        )
        .strip()
        .splitlines()[-1]
    )
    return "\n".join(rows), first


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".")
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    report_path = root / REPORT_PATH
    if not report_path.exists():
        print(f"report not found: {report_path}")
        return 1

    table_body, first = build_table()
    new_table = TABLE_HEADER + table_body

    text = report_path.read_text()
    start = text.index(TABLE_HEADER)
    end = text.index("\n\n**Note on the rewritten commit ids.**", start)
    updated = text[:start] + new_table + text[end:]

    updated = updated.replace(
        "This report was first published at commit `",
        "This report was first published at commit `",
    )
    # Keep the first-published reference in step with the history.
    import re

    updated = re.sub(
        r"This report was first published at commit `[0-9a-f]+`",
        f"This report was first published at commit `{first[:7]}`",
        updated,
    )

    if args.check:
        if updated != text:
            print("DRIFT: the revision history table is stale; run without --check")
            return 1
        print("revision history table is up to date")
        return 0

    report_path.write_text(updated)
    print(f"revision history table regenerated ({len(table_body.splitlines())} rows)")
    print(f"first published commit: {first[:7]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
